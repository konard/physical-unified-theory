(** ** A.4.1: Lie Algebras

    A Lie algebra (g, [·,·]) satisfies:
    - Bilinearity: [λX + Y, Z] = λ[X,Z] + [Y,Z]
    - Antisymmetry: [X,Y] = -[Y,X]
    - Jacobi identity: [X,[Y,Z]] + [Y,[Z,X]] + [Z,[X,Y]] = 0

    The su(2) algebra has generators {J₁, J₂, J₃} with
    [Jₐ, J_b] = ε_{abc} Jc. *)

(** The Levi-Civita symbol ε_{ijk} in 3D (antisymmetric).
    Returns 1 for even permutations of (0,1,2), -1 for odd, 0 otherwise. *)
Definition levi_civita (i j k : nat) : R :=
  if Nat.eqb i 0 && Nat.eqb j 1 && Nat.eqb k 2 then 1
  else if Nat.eqb i 1 && Nat.eqb j 2 && Nat.eqb k 0 then 1
  else if Nat.eqb i 2 && Nat.eqb j 0 && Nat.eqb k 1 then 1
  else if Nat.eqb i 2 && Nat.eqb j 1 && Nat.eqb k 0 then -1
  else if Nat.eqb i 0 && Nat.eqb j 2 && Nat.eqb k 1 then -1
  else if Nat.eqb i 1 && Nat.eqb j 0 && Nat.eqb k 2 then -1
  else 0.

(** The Levi-Civita symbol is antisymmetric in the first two indices. *)
Lemma levi_civita_antisym12 (i j k : nat) :
    levi_civita i j k = - levi_civita j i k.
Proof.
  unfold levi_civita.
  destruct i, j, k; simpl; try lra;
  repeat (destruct i; simpl; try lra);
  repeat (destruct j; simpl; try lra);
  repeat (destruct k; simpl; try lra).
Qed.

(** The Levi-Civita symbol vanishes when two indices are equal. *)
Lemma levi_civita_diag (i j : nat) : levi_civita i i j = 0.
Proof.
  unfold levi_civita.
  destruct i; simpl; try lra;
  repeat (destruct i; simpl; try lra).
Qed.

(** ** A.4.2: Representation Theory

    A representation of a Lie group G on V is ρ: G → GL(V).
    The spin-j representation of SU(2) has dimension 2j+1. *)

(** Dimension of the spin-j representation of SU(2).
    j is given as 2j (to keep it natural number). *)
Definition spin_rep_dim (j_twice : nat) : nat := j_twice + 1.

(** Spin-0 (scalar): dimension 1. *)
Lemma spin0_dimension : spin_rep_dim 0 = 1.
Proof. reflexivity. Qed.

(** Spin-1/2 (spinor): dimension 2. Describes electrons, quarks. *)
Lemma spin_half_dimension : spin_rep_dim 1 = 2.
Proof. reflexivity. Qed.

(** Spin-1 (vector): dimension 3. Describes gauge bosons (W, Z, gluons). *)
Lemma spin1_dimension : spin_rep_dim 2 = 3.
Proof. reflexivity. Qed.

(** Spin-3/2 (Rarita-Schwinger): dimension 4. Describes gravitino. *)
Lemma spin_3half_dimension : spin_rep_dim 3 = 4.
Proof. reflexivity. Qed.

(** Spin-2 (graviton): dimension 5. Describes the graviton. *)
Lemma spin2_dimension : spin_rep_dim 4 = 5.
Proof. reflexivity. Qed.

(** The Casimir operator for spin-j representation: J² = j(j+1)ℏ².
    In natural units: J² = j(j+1).
    j_twice = 2j. *)
Definition casimir_eigenvalue (j_twice : nat) : R :=
  let j := INR j_twice / 2 in
  j * (j + 1).

(** For spin-1/2: J² = (1/2)(3/2) = 3/4. *)
Lemma spin_half_casimir : casimir_eigenvalue 1 = 3/4.
Proof.
  unfold casimir_eigenvalue. simpl. lra.
Qed.

(** For spin-1: J² = 1 * 2 = 2. *)
Lemma spin1_casimir : casimir_eigenvalue 2 = 2.
Proof.
  unfold casimir_eigenvalue. simpl. lra.
Qed.

(** ** A.4.3: Clifford Algebra (Real Analogue)

    The Clifford algebra generators γ^μ satisfy {γ^μ, γ^ν} = 2η^{μν}.
    For the Euclidean case: {γⁱ, γʲ} = 2δⁱʲ.

    In the real 2D case, the Clifford algebra Cl(2,0) is generated by
    e₁, e₂ with e₁² = e₂² = 1 and e₁e₂ = -e₂e₁. *)

(** Clifford algebra element (linear combination of 1, e₁, e₂, e₁e₂). *)
Record CliffordAlg2 : Type := mkClifford {
  scalar_part : R;   (** coefficient of 1 *)
  e1_part : R;       (** coefficient of e₁ *)
  e2_part : R;       (** coefficient of e₂ *)
  e12_part : R       (** coefficient of e₁e₂ *)
}.

(** The unit element 1 in the Clifford algebra. *)
Definition clifford_one : CliffordAlg2 := {|
  scalar_part := 1; e1_part := 0; e2_part := 0; e12_part := 0
|}.

(** The generator e₁. *)
Definition clifford_e1 : CliffordAlg2 := {|
  scalar_part := 0; e1_part := 1; e2_part := 0; e12_part := 0
|}.

(** The generator e₂. *)
Definition clifford_e2 : CliffordAlg2 := {|
  scalar_part := 0; e1_part := 0; e2_part := 1; e12_part := 0
|}.

(** Clifford algebra multiplication (for Euclidean 2D: e₁²= e₂²= 1, e₁e₂= -e₂e₁). *)
Definition clifford_mul (a b : CliffordAlg2) : CliffordAlg2 := {|
  scalar_part := a.(scalar_part) * b.(scalar_part)
               + a.(e1_part) * b.(e1_part)
               + a.(e2_part) * b.(e2_part)
               - a.(e12_part) * b.(e12_part);
  e1_part := a.(scalar_part) * b.(e1_part)
           + a.(e1_part) * b.(scalar_part)
           - a.(e2_part) * b.(e12_part)
           + a.(e12_part) * b.(e2_part);
  e2_part := a.(scalar_part) * b.(e2_part)
           + a.(e1_part) * b.(e12_part)
           + a.(e2_part) * b.(scalar_part)
           - a.(e12_part) * b.(e1_part);
  e12_part := a.(scalar_part) * b.(e12_part)
            + a.(e1_part) * b.(e2_part)
            - a.(e2_part) * b.(e1_part)
            + a.(e12_part) * b.(scalar_part)
|}.

(** e₁² = 1 in the Euclidean Clifford algebra Cl(2,0). *)
Lemma e1_squared :
    clifford_mul clifford_e1 clifford_e1 = clifford_one.
Proof.
  unfold clifford_mul, clifford_e1, clifford_one.
  simpl. f_equal; lra.
Qed.

(** e₂² = 1 in the Euclidean Clifford algebra Cl(2,0). *)
Lemma e2_squared :
    clifford_mul clifford_e2 clifford_e2 = clifford_one.
Proof.
  unfold clifford_mul, clifford_e2, clifford_one.
  simpl. f_equal; lra.
Qed.

(** e₁e₂ + e₂e₁ = 0 (anticommutation relation). *)
Lemma e1_e2_anticommute :
    let e12 := clifford_mul clifford_e1 clifford_e2 in
    let e21 := clifford_mul clifford_e2 clifford_e1 in
    e12.(scalar_part) + e21.(scalar_part) = 0 /\
    e12.(e1_part) + e21.(e1_part) = 0 /\
    e12.(e2_part) + e21.(e2_part) = 0 /\
    e12.(e12_part) + e21.(e12_part) = 0.
Proof.
  unfold clifford_mul, clifford_e1, clifford_e2.
  simpl. repeat split; lra.
Qed.
